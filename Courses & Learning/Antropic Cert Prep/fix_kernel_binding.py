"""
Clear VS Code's stale notebook->interpreter binding for this workspace.

Why: VS Code pinned 001_requests.ipynb to the GLOBAL uv Python
(.local\\bin\\python3.14.exe), which has no ipykernel. The binding is cached
per-notebook in state.vscdb and survives window reloads, so the kernel picker
kept resolving back to the broken interpreter.

This deletes only cached selection state. VS Code rebuilds all of it on next
launch; nothing about your code, notebook, or .venv is touched.

Run with VS Code fully CLOSED:
    .venv\\Scripts\\python.exe fix_kernel_binding.py
"""

import json
import shutil
import sqlite3
import subprocess
import sys
import time
from pathlib import Path

WORKSPACE_DB = Path(
    r"C:\Users\TenchoBostandzhiev\AppData\Roaming\Code\User\workspaceStorage"
    r"\09381e5a9000dad51db0c065575fc29d\state.vscdb"
)

# Cached selection state only — all of it is regenerated by VS Code on startup.
KEYS_TO_DELETE = [
    "notebook.controller2NotebookBindings",  # the actual culprit
    "notebook.kernelHistory",                # remembers the bad kernel
    "ms-python.python",                      # autoSelectedWorkspacePythonInterpreter
    "ms-python.vscode-python-envs",          # stale "system" workspace selection
]


def vscode_running() -> bool:
    out = subprocess.run(
        ["tasklist", "/FI", "IMAGENAME eq Code.exe", "/NH"],
        capture_output=True, text=True,
    ).stdout
    return "Code.exe" in out


def main() -> int:
    if vscode_running():
        print("ERROR: VS Code is still running.")
        print("Close every VS Code window (check the tray too), then re-run.")
        print("Editing state.vscdb while it's open would just be overwritten on exit.")
        return 1

    if not WORKSPACE_DB.exists():
        print(f"ERROR: database not found:\n  {WORKSPACE_DB}")
        return 1

    backup = WORKSPACE_DB.with_suffix(f".vscdb.bak-{time.strftime('%Y%m%d-%H%M%S')}")
    shutil.copy2(WORKSPACE_DB, backup)
    print(f"Backup written:\n  {backup}\n")

    con = sqlite3.connect(WORKSPACE_DB)
    try:
        removed = []
        for key in KEYS_TO_DELETE:
            row = con.execute(
                "SELECT value FROM ItemTable WHERE key = ?", (key,)
            ).fetchone()
            if row is None:
                print(f"  (absent, nothing to do)  {key}")
                continue

            # Show what we're about to drop, so the change is auditable.
            raw = row[0]
            text = raw.decode("utf-8", "replace") if isinstance(raw, bytes) else str(raw)
            try:
                preview = json.dumps(json.loads(text))
            except Exception:
                preview = text
            print(f"  DELETING  {key}\n            {preview[:160]}")

            con.execute("DELETE FROM ItemTable WHERE key = ?", (key,))
            removed.append(key)

        con.commit()
    finally:
        con.close()

    print(f"\nDone - removed {len(removed)} key(s).")
    print("\nNext steps:")
    print("  1. Reopen the 'Antropic Cert Prep' folder in VS Code")
    print("  2. Open 001_requests.ipynb -> Select Kernel")
    print("  3. Choose: Python (Antropic Cert Prep .venv)")
    print("  4. Run cell 1 - it should print a path ending in .venv\\Scripts\\python.exe")
    print(f"\nTo undo, restore the backup over state.vscdb:\n  {backup}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
